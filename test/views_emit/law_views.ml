(* -- the emitted views ---------------------------------------------------------

      (a) The walk accounts for every child of every node. A child no slot
          takes is trivia, an error node, a token the lexer could not finish
          or classify, one of the frame's own tokens (its opener, its closer,
          its separator), or input a diagnostic reported as extra.
      (b) A placeholder fills the slot the parse was filling when it left it.
      (c) Every module the emitter wrote is what it writes now, byte for byte.
      (d) The slots are filled in order: a later child is never in an earlier
          slot, and a child that does not repeat holds one node at most.
      (e) Every type, module and constructor the views module defines is a
          manifest entry in the scope it lands in, and so is every accessor
          of a production's module. A name the manifest does not list is a
          name no collision check has seen.

      Mechanism. Fourteen grammars, and three corpora over each: the inputs in
      test/inputs, [Sweep]'s damaged copies of them, and draws from the
      grammar. The interpreter parses each one, and every node the result
      holds is walked by the emitted [Slots.slots].

      Part (b) has an oracle of its own. A placeholder's payload is the id of
      its [Missing] diagnostic, and that diagnostic names the child the parse
      was filling. The walk never reads a diagnostic, so the two agree only
      where the walk put the placeholder where the parse did.

      Two [Missing] reports over one range fold into one entry, which keeps the
      first one's child name. So (b) reads a placeholder only where its id
      first appears in source order, and only where the child its diagnostic names
      is one that takes a placeholder. A required token takes none, and a
      placeholder folded into a token's report names the token.

      test/views_emit/nested is the fourteenth, and it is here for the views
      alone. Its block has no token atom, so no base node, and one child's
      variant holds a block's position as an arm. No other grammar has either.

      Part (e) reads the emitted structure rather than the source text, so a
      name is classified by where it is defined. It is the cross-check
      test/laws/law_manifest.ml's header asks for, for this one emitter.

      What this says nothing about. Whether an accessor reads its slot right:
      which arm of a variant a node becomes, and that a placeholder reads as
      [None]. test/views_emit/test_views.ml reads those, through the typed
      modules, on inputs chosen for them.
   -------------------------------------------------------------------------- *)

