    (fun (what, g, want) ->
       let got = left_shape (rejections g) in
       if got <> want
       then Law.fail "(g) %s shows %s, where it should show %s" what got want)
    left;
  let operator_shape (es : Core.Error.t list) : string =
    String.concat
      "; "
      (List.filter_map
         (fun (e : Core.Error.t) ->
            match e.detail with
            | Core.Error.Operator_follow_conflict { block; common } ->
              Some
                (Printf.sprintf
                   "%s on %s"
                   (Core.Grammar.Name.Rule.to_string block)
                   (String.concat
                      ","
                      (List.map
                         (fun (k : Core.Error.kind_ref) ->
                            Core.Kind.Name.to_string k.name)
                         common)))
            | _ -> None)
         es)
  in
  let operator =
    [ "the witness", Lingo_witness.Witnesses.operator_follow_conflict, "E on T_T"
    ; ( "a repeated expression, whose next element can start with an operator"
      , create
          ~tokens
          ~roots:[ "Root" ]
          ~expr:
            [ expr_block
                ~rule_name:"E"
                ~atoms:[ Token "ta" ]
                ~prefix_ops:[ prefix ~token:"m" ~bp:70 () ]
                ~infix_ops:[ infix ~token:"m" ~bp:10 () ]
                ()
            ]
          [ prod "Root" [ child_rep "e" (Rule "E") ] ]
      , "E on T_M" )
    ; ( "an expression in brackets whose closer is an operator"
      , create
          ~tokens
          ~roots:[ "Root" ]
          ~expr:
            [ expr_block
                ~rule_name:"E"
                ~atoms:[ Token "ta" ]
                ~infix_ops:[ infix ~token:"rp" ~bp:10 () ]
                ()
            ]
          [ prod "Root" [ child_req "e" (Rule "E") ]
            |> with_delimited ~open_tok:"lp" ~close_tok:"rp"
          ]
      , "E on T_RP" )
    ]
  in
  List.iter
    (fun (what, g, want) ->
       let got = operator_shape (rejections g) in
       if got <> want
       then Law.fail "(g) %s reports %S, where it should report %S" what got want)
    operator;
  if Law.failures () = before
  then
    Law.pass
      "(g) every left recursion shows its way round and its rewrite, and every operator \
       conflict names its block, over %d grammars"
      (List.length left + List.length operator)
