(* -- every rejection is deserved ----------------------------------------------

      (a) For every code in [Error.codes] there is a witness grammar that
          provokes that code and no other.
      (b) [Error.codes] lists every code the checker emits: no witness
          produces one outside it.
      (c) Every check runs at the stage its code is filed under in
          [Error.codes_by_stage].
      (d) Every grammar in the accepted corpus yields a [Facts.t].
      (e) Findings come back sorted and free of duplicates.
      (f) One left-recursive cycle is one finding, whatever its length, and
          it shows the cycle in order.
      (g) A left recursion shows the shortest way round and the rewrite its
          shape suggests, and an operator conflict names its block and the
          operators that follow.

      Mechanism: an oracle over the witness corpus, with no baseline. Part (c)
      is a cross-check between the stage a code is filed under and the stage
      that emits it.

      Why each part is separate from the others. Part (a) compares sets of
      codes, so a check that reports one code k times collapses to the same set
      and (a) stays green; part (f) carries the count for that reason. Part (c)
      cross-checks the stage a code is filed under against the stage that emits
      it, so a check moved from one stage to another passes (a) and fails (c).
      Part (e) rejects findings that are identical, which a left recursion
      reported per member is not: the members differ in their site and message.
      Each part exists because the one beside it cannot see something.

      Part (g) reads the details the author sees. Parts (a) to (f) compare
      codes, so a report that showed the wrong path or suggested the wrong
      rewrite would pass all of them. Each detail is rendered as one line and
      compared with what the grammar's shape says it should be. One grammar
      has a longer way round beside the shortest, so a search that took the
      first path it found would show the wrong one.

      Why the left recursions report one code. Every left recursion also
      makes the child that carries it overlap what the rule takes first. The
      checker leaves that conflict out, so each of part (f)'s six cycles
      reports the recursion alone. Drop that and a cycle of n rules reports
      n conflicts beside it.

      Where a collision is recorded. The duplicate-child-name witness lives
      here rather than under test/laws/law_manifest.ml, because that law reads
      the manifest for the collision and finds it either way. This one reads
      whether the checker refused the grammar.

      The one test with a blast radius. Dropping the self-edge test on a
      one-rule component makes every rule a component of its own, so every
      grammar in the tree is rejected: 21 findings here, 15 in law_facts, 10
      each in law_first_follow and law_manifest, and one apiece from sexp_facts
      and pratt_desugar, because each needs a [Facts.t] the checker now refuses
      to build. That one test is what separates a rule from a rule that reaches
      itself.

      Why (c) is separate from (a). A check that moves stage keeps its witness
      rejected, so (a) still passes: the grammar is refused, just not where the
      code says it is refused. (c) is the part that reads the stage.

      Coverage. The 63 witness grammars and the 11 accepted ones: at least
      one grammar per rejection and a handful of near misses, together with
      the six cycles part (f) builds for itself. It says nothing about whether
      a check's reason is right, only that it fires on one shape and stays
      quiet on eleven others. Eleven accepted grammars is a statement about eleven
      grammars; a generated corpus is what would make it a statement about
      the checker.
   -------------------------------------------------------------------------- *)

