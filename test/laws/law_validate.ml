let codes_of = function
  | Ok _ -> []
  | Error es ->
    List.sort_uniq
      String.compare
      (List.map (fun (e : Core.Error.t) -> Core.Error.code e) es)
;;

let stage_of_code (code : string) : string option =
  List.find_map
    (fun (stage, cs) -> if List.mem code cs then Some stage else None)
    Core.Error.codes_by_stage
;;

(* (a) and (b) *)
let () =
  List.iter
    (fun (code, g) ->
       match codes_of (Core.Facts.of_grammar g) with
       | [] -> Law.fail "%s: the witness grammar was accepted" code
       | [ c ] when c = code -> Law.pass "%s: witness provokes exactly it" code
       | cs ->
         Law.fail
           "%s: witness provokes {%s} instead of exactly it"
           code
           (String.concat ", " cs))
    Lingo_witness.Witnesses.all
;;

let () =
  let witnessed =
    List.sort_uniq String.compare (List.map fst Lingo_witness.Witnesses.all)
  in
  let declared = List.sort_uniq String.compare Core.Error.codes in
  List.iter
    (fun c ->
       if not (List.mem c witnessed)
       then
         Law.fail
           "%s is in Error.codes but has no witness: it is untested or unreachable, and \
            both are findings"
           c)
    declared;
  List.iter
    (fun c ->
       if not (List.mem c declared) then Law.fail "%s is emitted but not in Error.codes" c)
    witnessed;
  if List.length Core.Error.codes <> List.length declared
  then Law.fail "Error.codes contains a duplicate";
  List.iter
    (fun c ->
       if stage_of_code c = None
       then Law.fail "%s is in Error.codes but in no stage list" c)
    declared;
  if Law.failures () = 0
  then Law.pass "Error.codes and the witness table are the same set"
;;

(* (c). The one caller of [Internal]. A code filed under "names" and caught
   at the third stage passes the completeness law while reporting two
   derivations later than it could, and running the stages one at a time is
   how that shows. *)

let () =
  List.iter
    (fun (code, g) ->
       let declared = Option.get (stage_of_code code) in
       let n = Core.Internal.Stage.names g in
       let s1 = Core.Internal.Check_names.run n in
       let observed =
         if s1 <> []
         then "names"
         else (
           let shape = Core.Internal.Stage.shape n in
           if Core.Internal.Check_shape.run shape <> []
           then "shape"
           else if
             Core.Internal.Check_full.run
               shape
               (Core.Internal.Fixpoint.compute
                  ~rules:shape.rules
                  ~blocks:shape.blocks
                  ~kind_rule:shape.names.kind_rule)
               (Core.Internal.Stage.lexer n)
             <> []
           then "full"
           else "accepted")
       in
       if observed = declared
       then Law.pass "%s: rejected at stage %s, as filed" code declared
       else Law.fail "%s: filed under stage %s but rejected at %s" code declared observed)
    Lingo_witness.Witnesses.all
;;

(* (e). Several checks build their reports by folding a hash table, so the
   sort is what fixes the order a caller sees. *)
let () =
  List.iter
    (fun (code, g) ->
       match Core.Facts.of_grammar g with
       | Ok _ -> ()
       | Error es ->
         if List.sort Core.Error.compare es <> es
         then Law.fail "%s: findings are not sorted" code
         else if List.sort_uniq Core.Error.compare es <> es
         then Law.fail "%s: findings contain a duplicate" code)
    Lingo_witness.Witnesses.all;
  if Law.failures () = 0 then Law.pass "findings are sorted and duplicate-free"
