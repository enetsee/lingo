(* One left recursion's members, its way round and its rewrite, as one line. *)
let left_shape (es : Core.Error.t list) : string =
  let rule = Core.Grammar.Name.Rule.to_string in
  let found =
    List.filter_map
      (fun (e : Core.Error.t) ->
         match e.detail with
         | Core.Error.Left_recursion { members; steps; rewrite } ->
           Some (members, steps, rewrite)
         | _ -> None)
      es
  in
  match found with
  | [ (members, steps, rewrite) ] ->
    let step (s : Core.Error.left_step) =
      match s.through with
      | Core.Error.Through_child c ->
        Printf.sprintf
          "%s -%s-> %s"
          (rule s.rule)
          (Core.Grammar.Name.Child.to_string c)
          (rule s.reaches)
      | Core.Error.Through_atom ->
        Printf.sprintf "%s -atom-> %s" (rule s.rule) (rule s.reaches)
    in
    let rewrite =
      match rewrite with
      | Core.Error.Repeat { rule = r; child } ->
        Printf.sprintf "repeat %s.%s" (rule r) (Core.Grammar.Name.Child.to_string child)
      | Core.Error.Operator { block; rule = r; lead; infix } ->
        Printf.sprintf
          "%s %s of %s on %s"
          (if infix then "infix" else "postfix")
          (rule r)
          (rule block)
          (Core.Grammar.Name.Token.to_string lead)
      | Core.Error.Break_cycle -> "break"
    in
    Printf.sprintf
      "%s | %s | %s"
      (String.concat "," (List.map rule members))
      (String.concat ", " (List.map step steps))
      rewrite
  | ds -> Printf.sprintf "%d left recursions" (List.length ds)
;;

(* (f). The property is about the length of the cycle and the witness table
   fixes two lengths, so these are built here and quantified over. A cycle of
   one is the length at which reporting rotations and reporting components
   agree, which is why the corpus on its own could not separate them. *)
let () =
  let name i = Printf.sprintf "P%d" i in
  let cycle n =
    Grammar.create
      ~tokens:[ Grammar.punct_tight ~name:"ta" "a" ]
      ~roots:[ name 0 ]
      (List.init n (fun i ->
         Grammar.prod
           (name i)
           [ Grammar.child_opt "l" (Grammar.Rule (name ((i + 1) mod n)))
           ; Grammar.child_req "t" (Grammar.Token "ta")
           ]))
  in
  List.iter
    (fun n ->
       match Core.Facts.of_grammar (cycle n) with
       | Ok _ -> Law.fail "a cycle of %d rules was accepted" n
       | Error es ->
         let want =
           Printf.sprintf
             "%s | %s | %s"
             (String.concat "," (List.init n name))
             (String.concat
                ", "
                (List.init n (fun i -> name i ^ " -l-> " ^ name ((i + 1) mod n))))
             (if n = 1 then "repeat P0.l" else "break")
         in
         (match left_shape es with
          | got when got = want -> ()
          | got ->
            Law.fail "a cycle of %d rules shows %s, where it should show %s" n got want);
         let mine =
           List.filter (fun (e : Core.Error.t) -> Core.Error.code e = "left-recursion") es
         in
         if List.length es <> 1 || List.length mine <> 1
         then
           Law.fail
             "a cycle of %d rules reports %d findings, %d of them left-recursion: one \
              cycle is one left recursion"
             n
             (List.length es)
             (List.length mine))
    [ 1; 2; 3; 4; 5; 8 ];
  if Law.failures () = 0
  then Law.pass "one left recursion is one finding, at every cycle length"
;;

(* (g) *)
let () =
  let before = Law.failures () in
  let open Core.Grammar in
  let tokens =
    [ punct_tight ~name:"ta" "a"
    ; punct_tight ~name:"tb" "b"
    ; punct_tight ~name:"m" "-"
    ; punct_tight ~name:"lp" "("
    ; punct_tight ~name:"rp" ")"
    ; punct_tight ~name:"comma" ","
    ]
  in
  let rejections (g : t) : Core.Error.t list =
    match Core.Facts.of_grammar g with
    | Ok _ -> []
    | Error es -> es
  in
  let left =
    [ ( "the direct witness"
      , Lingo_witness.Witnesses.left_recursion
      , "Root | Root -l-> Root | repeat Root.l" )
    ; ( "the pair witness"
      , Lingo_witness.Witnesses.left_recursion_pair
      , "Root,Inner | Root -l-> Inner, Inner -l-> Root | break" )
    ; ( "the operator witness"
      , Lingo_witness.Witnesses.left_recursion_operator
      , "Add,E | Add -l-> E, E -atom-> Add | infix Add of E on t" )
    ; ( "an atom that ends in a token"
      , create
          ~tokens
          ~roots:[ "Root" ]
          ~expr:[ expr_block ~rule_name:"E" ~atoms:[ Token "ta"; Rule "Call" ] () ]
          [ prod "Root" [ child_req "e" (Rule "E") ]
          ; prod
              "Call"
              [ child_req "f" (Rule "E")
              ; child_req "lp" (Token "lp")
              ; child_req "rp" (Token "rp")
              ]
          ]
      , "Call,E | Call -f-> E, E -atom-> Call | postfix Call of E on lp" )
    ; ( "a cycle with a longer way round beside the shortest"
      , create
          ~tokens
          ~roots:[ "A" ]
          [ prod "A" [ child_opt "b" (Rule "B"); child_req "t" (Token "ta") ]
          ; prod
              "B"
              [ child_opt "c" (Rule "C")
              ; child_opt "a" (Rule "A")
              ; child_req "t" (Token "tb")
              ]
          ; prod "C" [ child_opt "a" (Rule "A"); child_req "t" (Token "m") ]
          ]
      , "A,B,C | A -b-> B, B -a-> A | break" )
    ]
  in
