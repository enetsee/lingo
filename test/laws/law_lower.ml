(* -- the lowering -------------------------------------------------------------

      (a) [Check.run] accepts every plan [of_facts] builds.
      (b) Every message id in a plan indexes the catalogue beside it.
      (c) Every catalogue entry is named by at least one id in the plan.
      (d) Every constructor of [Ir.Plan.instr], and every form beside it, is
          one the corpus lowers to.
      (e) A negative kind is reported wherever a plan can hold one.
      (f) An index out of range is reported wherever a plan can hold one, an
          index in range never is, and an empty dispatch set is reported
          wherever a plan can hold one.

      Mechanism. Part (a) makes every invariant [Check] holds a post-condition
      of the lowering, rather than a fact about the plans that happen to be in
      test/expect. There are fourteen of them and this law restates none.

      Parts (b) and (c) are one walk over the plan, collecting the ids it
      names, against the catalogue's length. The walk is this law's own: the
      lowering interns an id where it needs one, and this counts them off the
      plan afterwards.

      Part (c) is the one that bites. [Messages.Builder.intern] dedupes on the
      text, so an id no instruction uses disappears wherever its
      wording matches a live entry. It only shows up on wording that is
      unique, which is rare enough to survive a reading of the catalogue and
      not a law.

      Part (d) is the claim that a plan constructor nobody can build is one
      nobody should have written. test/laws/law_plan.ml counts forms too, and
      it counts them over a plan built by hand, so a constructor reaches its
      tally because someone typed it. This one counts over the grammars, so a
      form reads zero until a grammar exists that needs it.

      Coverage. All thirteen grammars in lingo_grammars, and the six accepted
      witnesses built in test/laws/witnesses.ml. required-empty is the one that
      matters to part (a): it has required children that can match nothing,
      and a lowering that put a commit over one would fail here. A count
      prints beside the result, part (c) fails on the first entry nothing
      names, and part (d) names every form that reads zero.

      What this says nothing about. Whether the plan describes the grammar.
      That needs something that runs one, and test/laws/law_interp.ml is where
      that starts.

      Why shapes carries a wording of its own. [intern] dedupes on the text, so
      a message interned for a child that never reports disappears into a live
      entry wherever its wording matches one. shapes gives its optional child a
      wording nothing else uses for that reason and for no other; wide came with
      a second by accident. Without them the leak is invisible.

      What part (d) is and is not. It reads zero or not zero, so a lowering that
      emits a form less often still passes: the claim is about the plan's surface
      rather than about how much of it the corpus uses. It exists because
      [Ir.Plan.Cannot_exit] sat in the plan for a while with no grammar able to
      build one and no parse able to act on one, and test/laws/law_plan.ml
      counted it as reached because its fixture is written by hand.

   -------------------------------------------------------------------------- *)

